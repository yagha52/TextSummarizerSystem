from nltk.tokenize import sent_tokenize

def lead3_baseline(article: str) -> str:
    """Returns the first 3 sentences of the article as a summary."""
    sentences = sent_tokenize(article)
    return " ".join(sentences[:3])

if __name__ == "__main__":
    # Load the test set generated by Person A's preprocess.py
    test_file = "data/processed/test.jsonl"
    
    if not os.path.exists(test_file):
        print(f"Error: {test_file} not found. Please run data/preprocess.py first.")
        exit(1)
        
    predictions = []
    references = []
    
    print("Running Lead-3 baseline on test set...")
    with open(test_file, "r", encoding="utf-8") as f:
        for line in f:
            sample = json.loads(line)
            # The text format:
            # ### Instruction:\n...\n\n### Article:\n{article}\n\n### Summary:\n{summary}
            text = sample["text"]
            parts = text.split("### Summary:\n")
            if len(parts) == 2:
                article_part = parts[0].split("### Article:\n")[1].strip()
                reference_summary = parts[1].strip()
                
                prediction = lead3_baseline(article_part)
                
                predictions.append(prediction)
                references.append(reference_summary)
                
    if not predictions:
        print("No samples found!")
        exit(1)
        
    print(f"Computed baselines for {len(predictions)} samples. Calculating ROUGE...")
    scores = compute_rouge(predictions, references)
    
    print("\n--- BASELINE ROUGE SCORES ---")
    for k, v in scores.items():
        print(f"{k}: {v:.4f}")
        
    os.makedirs("evaluation/results", exist_ok=True)
    output_path = "evaluation/results/baseline_scores.json"
    with open(output_path, "w") as f:
        json.dump(scores, f, indent=4)
        
    print(f"\nBaseline scores saved to {output_path}")
